import { generateHeuristicQuestions } from '../lib/chunker';
import { TrainingPassage } from '../types/schema';

interface RawPresetSeed {
  id: string;
  title: string;
  category: string;
  difficultyGrade: number;
  chunks: string[];
  questions: TrainingPassage['questions'];
}

const DISCOURSE_MARKER_REGEX =
  /\b(however|therefore|consequently|nevertheless|furthermore|moreover|in contrast|conversely|ultimately|instead|nonetheless|meanwhile|thus|hence)\b/i;

function buildPassage(seed: RawPresetSeed, index: number): TrainingPassage {
  const rawText = seed.chunks.join(' ');
  const wordCount = rawText.split(/\s+/).filter(Boolean).length;
  const discourseMarkerIndices: number[] = [];

  seed.chunks.forEach((chunk, idx) => {
    if (DISCOURSE_MARKER_REGEX.test(chunk)) {
      discourseMarkerIndices.push(idx);
    }
  });

  // Combine the 3 curated conceptual questions with 6 contextual Cloze questions
  // so every passage has a diverse 9-question pool sampled randomly per session.
  const clozePool = generateHeuristicQuestions(seed.title, rawText, 6).map(
    (q, qIdx) => ({
      ...q,
      id: `${seed.id}-cloze-${qIdx + 1}`,
    })
  );

  return {
    id: seed.id,
    sourceType: 'preset',
    title: seed.title,
    category: seed.category,
    wordCount,
    difficultyGrade: seed.difficultyGrade,
    rawText,
    chunks: seed.chunks,
    discourseMarkerIndices,
    questions: [...seed.questions, ...clozePool],
    createdAt: 1760000000000 + index * 3600000,
  };
}

